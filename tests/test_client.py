def test_discover_languages_uses_metadata(response):
    response["source"] = "youtube_metadata"
    response["results"] = [{"videoId": "DEMO0000001", "transcriptLanguages": ["es", "en", "en"]}]

    def handler(request):
        assert json.loads(request.content) == {
            "source": "youtube_metadata",
            "video_id": "DEMO0000001",
            "params": {"include_formats": False, "include_chapters": False},
        }
        return httpx.Response(200, json=response)

    with sdk_for(handler) as sdk:
        assert TranscriptClient(sdk=sdk).languages("DEMO0000001") == ["en", "es"]


@pytest.mark.parametrize("failure", ["network", "http"])
def test_submissions_are_never_automatically_retried(failure):
    calls = []

    def handler(request):
        calls.append(request)
        if failure == "network":
            raise httpx.ReadTimeout("simulated", request=request)
        return httpx.Response(429, json={"message": "Rate limited"})

    with sdk_for(handler) as sdk:
        expected = SubmissionUnknownError if failure == "network" else APIError
        with pytest.raises(expected):
            TranscriptClient(sdk=sdk).fetch("DEMO0000001")
    assert len(calls) == 1


def test_borrowed_sdk_remains_open(response):
    with sdk_for(lambda _: httpx.Response(200, json=response)) as sdk:
        with TranscriptClient(sdk=sdk) as client:
            client.fetch("DEMO0000001")
        assert not sdk._http.is_closed
        sdk.youtube.transcript("DEMO0000001")


@pytest.mark.parametrize(
    "kwargs",
    [
        {"language": ""},
        {"language": "English!"},
        {"auto": "true"},
    ],
)
def test_invalid_inputs_do_not_make_requests(kwargs):
    calls = []
    with sdk_for(lambda request: calls.append(request)) as sdk:
        with pytest.raises(ValueError):
            TranscriptClient(sdk=sdk).fetch("DEMO0000001", **kwargs)
    assert calls == []
