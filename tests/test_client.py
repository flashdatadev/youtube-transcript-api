import json
from copy import deepcopy

import httpx
import pytest
from flashdata import APIError, FlashData, SubmissionUnknownError

from flashdata_transcript import ResponseError, RetrievalFailed, TranscriptClient


def sdk_for(handler):
    return FlashData(api_key="test-key", transport=httpx.MockTransport(handler), trust_env=False)


def test_fetch_uses_official_sdk_contract(response):
    calls = []

    def handler(request):
        calls.append(request)
        assert str(request.url) == "https://data.flashdata.dev/v1/queries/realtime"
        assert request.method == "POST"
        assert request.headers["x-api-key"] == "test-key"
        assert json.loads(request.content) == {
            "source": "youtube_transcript",
            "video_id": "DEMO0000001",
            "params": {"language": "en", "auto": True},
        }
        return httpx.Response(200, json=response)

    with sdk_for(handler) as sdk, TranscriptClient(sdk=sdk) as client:
        transcript = client.fetch("https://youtu.be/DEMO0000001?t=2", language="en")
        assert transcript.language_code == "en-orig"
        assert transcript.requested_language_code == "en"
        assert transcript.segments[0].duration == 1.25
        assert transcript.source_url == "https://www.youtube.com/watch?v=DEMO0000001"
        assert len(calls) == 1
        assert "test-key" not in repr(client)


def test_manual_and_default_language(response):
    response["results"][0]["isAutoGenerated"] = False
    calls = []

    def handler(request):
        calls.append(json.loads(request.content))
        return httpx.Response(200, json=response)

    with sdk_for(handler) as sdk, TranscriptClient(sdk=sdk) as client:
        client.fetch("DEMO0000001", auto=False)
    assert calls[0]["params"] == {"auto": False}


@pytest.mark.parametrize(
    "mutate",
    [
        lambda value: value["results"][0].update(videoId="DEMO0000002"),
        lambda value: value["results"].append(deepcopy(value["results"][0])),
        lambda value: value["results"][0].update(isAutoGenerated=False),
        lambda value: value["results"][0].update(requestedLanguageCode="es"),
        lambda value: value["results"][0].pop("segments"),
        lambda value: value.update(status="running"),
    ],
)
def test_response_mismatches_are_not_silent(response, mutate):
    mutate(response)
    with sdk_for(lambda _: httpx.Response(200, json=response)) as sdk:
        with pytest.raises(ResponseError):
            TranscriptClient(sdk=sdk).fetch("DEMO0000001", language="en")


def test_known_failed_job(response):
    response.update(status="failed", results=[])
    with sdk_for(lambda _: httpx.Response(200, json=response)) as sdk:
        with pytest.raises(RetrievalFailed) as error:
            TranscriptClient(sdk=sdk).fetch("DEMO0000001")
        assert error.value.job_id == "job_test"


def test_multi_language_partial_results(track, response):
    response["results"] = [
        {
            "videoId": "DEMO0000001",
            "tracks": [track],
            "errors": [{"languageCode": "es", "code": "language_unavailable", "message": "No es."}],
        }
    ]

    def handler(request):
        assert json.loads(request.content)["params"]["language"] == ["en", "es"]
        return httpx.Response(200, json=response)

    with sdk_for(handler) as sdk:
        result = TranscriptClient(sdk=sdk).fetch_languages("DEMO0000001", ["en", "es"])
    assert not result.ok
    assert len(result.tracks) == 1
    assert result.errors[0].language_code == "es"
    assert result.to_dict()["errors"][0]["code"] == "language_unavailable"


